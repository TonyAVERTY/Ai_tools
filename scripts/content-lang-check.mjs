// Vérifie dans un vrai navigateur la langue des contenus d'un projet : le sélecteur de la création, son enregistrement, le changement dans les réglages du projet
// (sans recharger toute la page), et que la marque s'écrit « IaBoss ». Nécessite Playwright (PLAYWRIGHT_MODULE, PLAYWRIGHT_CHROMIUM). Sortie « TOUT EST BON » attendue.
import { startApp, APP_URL } from '../test/helpers/server.js';
import { testTokenLink } from '../test/helpers/users.js';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const exe = process.env.PLAYWRIGHT_CHROMIUM;
const s = await startApp();
const u = await s.newUser({ admin: false, link: testTokenLink() });
const b = await chromium.launch(exe ? { executablePath: exe } : {});
let bad = 0;
const ok = (c, m) => { console.log(`${c ? 'OK ' : 'KO '} ${m}`); if (!c) bad++; };
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
const [name, value] = u.cookie.split('=');
await ctx.addCookies([{ name, value, url: s.base }, { name: 'lang', value: 'en', url: s.base }]);
await ctx.route('**/*', async (route) => { const r = route.request(); if (r.method() !== 'POST') return route.continue(); await route.fulfill({ response: await route.fetch({ headers: { ...r.headers(), origin: APP_URL }, maxRedirects: 0 }) }); });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
await p.goto(`${s.base}/projets`);
await p.waitForSelector('html[data-nav="ready"]');
ok(/IaBoss/.test(await p.locator('body').innerText()) && !/\biaboss\b/.test(await p.locator('body').innerText()), 'la marque s\'écrit IaBoss dans le texte visible');
await p.locator('[data-new-toggle]').first().click();
const sel = p.locator('#new-project select[name="content_lang"]');
ok(await sel.isVisible(), 'le formulaire de création propose la langue des contenus');
ok((await sel.inputValue()) === 'en', 'elle est préchoisie dans la langue du site (English)');
ok(/Content language/.test(await p.locator('#new-project').innerText()), 'son libellé est traduit');
await sel.selectOption('es');
await p.fill('#new-project input[name="name"]', 'Atelier');
await p.fill('#new-project input[name="gitUrl"]', 'https://github.com/o/atelier.git');
await p.locator('#new-project button.primary').click();
await p.waitForFunction(() => /\/projets/.test(location.pathname), null, { timeout: 5000 }).catch(() => {});
await p.waitForTimeout(2500);
const row = await s.db.prepare('SELECT id, content_lang FROM projects WHERE name = ?').get('Atelier');
ok(row?.content_lang === 'es', `le projet est créé avec la langue choisie (${row?.content_lang})`);
await p.goto(`${s.base}/p/${row.id}/reglages`);
await p.waitForSelector('html[data-nav="ready"]');
const form = p.locator('form[data-action="content-lang"]');
await form.scrollIntoViewIfNeeded();
ok((await form.locator('select').inputValue()) === 'es', 'les réglages du projet montrent la langue enregistrée');
await form.locator('select').selectOption('fr');
await form.locator('button').click();
await p.waitForTimeout(1200);
ok((await s.db.prepare('SELECT content_lang l FROM projects WHERE id = ?').get(row.id)).l === 'fr', 'le changement est enregistré sans recharger la page');
ok(/Content language saved/.test(await p.locator('body').innerText()), 'le message de confirmation est traduit');
ok(!errs.length, `aucune erreur dans la console${errs.length ? ' : ' + errs[0] : ''}`);
await b.close();
await s.close();
console.log(bad ? `\n${bad} échec(s)` : '\nTOUT EST BON');
process.exit(bad ? 1 : 0);
